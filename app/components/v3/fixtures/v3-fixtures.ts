export const v3TreesById = (id: string): V3PreviewTree | undefined =>
  v3Trees.find((tree) => tree.id === id);

export const v3MemoriesByTree = (treeId: string): V3PreviewMemory[] =>
  v3Memories.filter((memory) => memory.treeId === treeId);

export const v3ChildrenOf = (memoryId: string): V3PreviewMemory[] =>
  v3Memories.filter((memory) => memory.parentId === memoryId);

export const v3RootMemories = (treeId: string): V3PreviewMemory[] =>
  v3Memories.filter((memory) => memory.treeId === treeId && !memory.parentId);

